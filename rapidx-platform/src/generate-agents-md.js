'use strict';

const fs = require('fs');
const path = require('path');

/**
 * Generate AGENTS.md content for cross-tool compatibility.
 * This file is read by Cursor, Codex, and GitHub Copilot.
 * @param {object} profile - Loaded profile object
 * @param {object} stack   - Stack configuration
 * @param {object} components - { rules: Set, skills: Set, agents: Set, hooks: Set }
 * @returns {string}
 */
function generateAgentsMd(profile, stack, components) {
  const clientName = profile.client_name || 'RapidX Project';
  const profileId = profile.profile_id || 'default';

  const agents = components ? Array.from(components.agents) : (profile.agents || []);
  const skills = components ? Array.from(components.skills) : (profile.skills || []);

  const fe = stack.frontend || {};
  const be = stack.backend || {};
  const db = stack.database || {};

  const stackSummary = [
    fe.framework ? `${fe.framework}${fe.version ? ' ' + fe.version : ''}` : null,
    be.language ? `${be.language}${be.language_version ? ' ' + be.language_version : ''}` : null,
    be.framework ? be.framework : null,
    db.primary ? db.primary : null,
  ].filter(Boolean).join(' · ');

  // Agent descriptions
  const agentDocs = {
    planner: 'Plans project phases, requirements, and roadmap. Use for new features and project planning.',
    architect: 'System design, architecture decisions, and technical roadmaps. Use for architectural questions.',
    'tdd-guide': 'Test-driven development guidance. Use when writing tests or doing TDD cycles.',
    'code-reviewer': 'Code quality review. Use for PR reviews and quality gates.',
    'security-reviewer': 'Security analysis and vulnerability detection. Use for auth, payments, and sensitive features.',
    'build-error-resolver': 'Diagnoses and resolves build errors, compilation failures, and CI issues.',
    'doc-updater': 'Keeps documentation in sync with code changes.',
    'e2e-runner': 'End-to-end test orchestration with Playwright/Cypress.',
    'refactor-cleaner': 'Code refactoring, cleanup, and technical debt reduction.',
    'database-reviewer': 'Database schema review, query optimization, and migration safety.',
    'spec-writer': 'Writes EARS-notation feature specifications, requirements docs, and implementation plans.',
    'knowledge-curator': 'Captures and maintains project knowledge, architecture patterns, and team conventions in .rapidx/knowledge/.',
    'workflow-orchestrator': 'Orchestrates multi-agent Get Things Done SDLC pipelines across Plan→Build→Review→Test→Ship phases.',
    'adr-writer': 'Writes Architecture Decision Records (ADRs) in MADR format with context, options, and consequences.',
    'csharp-reviewer': 'C#/.NET code review: SOLID principles, async correctness, EF Core patterns, ASP.NET Core security.',
    'go-reviewer': 'Go-specific code review: idiomatic patterns, concurrency safety, interface design, error handling.',
    'go-build-resolver': 'Resolves Go build errors, module issues, import cycles, and type mismatches.',
    'python-reviewer': 'Python-specific code review: type hints, async correctness, Django/FastAPI/Flask patterns, security.',
  };

  const agentSection = agents.map(a => {
    const desc = agentDocs[a] || `${a} agent`;
    return `### ${a}\n${desc}`;
  }).join('\n\n');

  const skillsSection = skills.map(s => `- \`${s}\``).join('\n');

  return `# AGENTS.md — ${clientName}

> Generated by RapidX Agentic Engineering Platform
> Profile: ${profileId} | Tech stack: ${stackSummary || 'not configured'}
> Last updated: ${new Date().toISOString()}

This file configures AI agent behavior for Cursor, Codex, and GitHub Copilot.

## Available agents

${agentSection}

## Delegation rules

- For new features: start with **planner** → **architect** → **tdd-guide**
- For bug fixes: start with **build-error-resolver** → **code-reviewer**
- For security concerns: always involve **security-reviewer**
- For database changes: always involve **database-reviewer**
- For documentation: delegate to **doc-updater** after code changes
- For end-to-end tests: delegate to **e2e-runner**

## Active skills

These skills are loaded as context for all agents:

${skillsSection}

## Tech stack context

${fe.framework ? `**Frontend:** ${fe.framework}${fe.version ? ' ' + fe.version : ''}` : ''}
${be.language ? `**Backend:** ${be.language}${be.language_version ? ' ' + be.language_version : ''}${be.framework ? ' + ' + be.framework : ''}` : ''}
${db.primary ? `**Database:** ${db.primary}${db.primary_version ? ' ' + db.primary_version : ''}` : ''}

## Version constraints

Always use the versions listed above. Do NOT suggest features from newer versions unless explicitly asked.

## Workflow

This project uses the **Get Things Done** workflow:
1. \`/rapidx:new-project\` or \`/rapidx:new-milestone\` — Start
2. \`/rapidx:plan-phase\` — Plan a phase
3. \`/rapidx:execute-phase\` — Execute
4. \`/rapidx:verify-work\` — Verify
5. \`/rapidx:ship\` — Ship

## RapidX commands

- \`/rapidx:help\` — All commands
- \`/rapidx:switch-client\` — Change profile
- \`/rapidx:add-tech\` — Add technology
- \`/rapidx:governance-check\` — Governance audit
`;
}

/**
 * Write AGENTS.md to a directory.
 */
function writeAgentsMd(targetDir, profile, stack, components) {
  const content = generateAgentsMd(profile, stack, components);
  const outPath = path.join(targetDir, 'AGENTS.md');
  fs.writeFileSync(outPath, content, 'utf8');
  return outPath;
}

module.exports = { generateAgentsMd, writeAgentsMd };
