'use strict';

const fs = require('fs');
const path = require('path');

/**
 * Generate CLAUDE.md content from profile and stack data.
 * @param {object} profile - Loaded profile object
 * @param {object} stack   - Stack configuration from stack.json
 * @param {object} components - { rules: Set, skills: Set, agents: Set, hooks: Set }
 * @returns {string} Generated CLAUDE.md content
 */
function generateClaudeMd(profile, stack, components) {
  const clientName = profile.client_name || 'RapidX Project';
  const profileId = profile.profile_id || 'default';
  const maturity = (profile.engagement && profile.engagement.maturity_level) || 'L1';
  const engType = (profile.engagement && profile.engagement.type) || 'greenfield';

  // Tech stack strings
  const fe = stack.frontend || {};
  const be = stack.backend || {};
  const db = stack.database || {};
  const infra = stack.infrastructure || {};
  const testing = stack.testing || {};
  const mobile = stack.mobile || null;

  const feStr = fe.framework ? `${fe.framework}${fe.version ? ' ' + fe.version : ''}` : null;
  const beStr = be.language ? `${be.language}${be.language_version ? ' ' + be.language_version : ''}` + (be.framework ? ` + ${be.framework}${be.framework_version ? ' ' + be.framework_version : ''}` : '') : null;
  const dbStr = db.primary ? `${db.primary}${db.primary_version ? ' ' + db.primary_version : ''}` + (db.orm ? ` + ${db.orm}` : '') : null;
  const infraStr = [
    infra.cloud,
    ...(infra.containers || []),
    ...(infra.cicd || []),
  ].filter(Boolean).join(', ');
  const testStr = [
    ...(testing.unit || []),
    ...(testing.e2e || []),
  ].filter(Boolean).join(', ');

  const rulesList = components ? Array.from(components.rules).join(', ') : (profile.rules || []).join(', ');
  const skillsList = components ? Array.from(components.skills).join(', ') : (profile.skills || []).join(', ');
  const agentsList = components ? Array.from(components.agents).join(', ') : (profile.agents || []).join(', ');

  // Version-specific guidance
  const versionGuidance = [];
  if (fe.framework && fe.version) {
    versionGuidance.push(`- Use ${fe.framework} ${fe.version} patterns and APIs. Do NOT use features introduced in newer versions.`);
  }
  if (be.language && be.language_version) {
    versionGuidance.push(`- Use ${be.language} ${be.language_version} features. Do NOT suggest features from later versions.`);
  }
  if (be.framework && be.framework_version) {
    versionGuidance.push(`- Use ${be.framework} ${be.framework_version} APIs. Do NOT use features from newer versions.`);
  }
  if (db.primary && db.primary_version) {
    versionGuidance.push(`- Use ${db.primary} ${db.primary_version} features. Avoid syntax only available in newer versions.`);
  }
  if (db.orm && db.orm_version) {
    versionGuidance.push(`- Use ${db.orm} ${db.orm_version} APIs. Do NOT use features from newer versions.`);
  }

  // Review gates
  const reviewGates = (profile.review_gates || []).map(g => `- **${g.name || g}**: ${g.description || ''}`).join('\n');

  const governanceSection = profile.governance ? `
## Governance & Compliance

${profile.governance.compliance_frameworks ? '**Compliance frameworks:** ' + profile.governance.compliance_frameworks.join(', ') : ''}
${profile.governance.audit_trail ? '- Audit trail: enabled' : ''}
${profile.governance.secret_scanning ? '- Secret scanning: enabled' : ''}
${profile.governance.mandatory_review ? '- Mandatory human review gates active' : ''}
` : '';

  return `# CLAUDE.md — ${clientName}

> Generated by RapidX Agentic Engineering Platform
> Profile: ${profileId} | Maturity: ${maturity} | Engagement: ${engType}
> Last updated: ${new Date().toISOString()}

## Project overview

**Client:** ${clientName}
**Profile:** ${profileId}
**Maturity level:** ${maturity}
**Engagement type:** ${engType}

## Technology stack

${feStr ? `**Frontend:** ${feStr}` : ''}
${be.ui_library && be.ui_library.length ? `**UI library:** ${[].concat(be.ui_library || fe.ui_library || []).join(', ')}` : ''}
${beStr ? `**Backend:** ${beStr}` : ''}
${be.api_style && be.api_style.length ? `**API style:** ${be.api_style.join(', ')}` : ''}
${dbStr ? `**Database:** ${dbStr}` : ''}
${db.cache && db.cache.length ? `**Cache:** ${db.cache.join(', ')}` : ''}
${infraStr ? `**Infrastructure:** ${infraStr}` : ''}
${testStr ? `**Testing:** ${testStr}` : ''}
${mobile ? `**Mobile:** ${mobile.framework || ''}` : ''}

## Version-specific constraints

${versionGuidance.length ? versionGuidance.join('\n') : '- No specific version constraints configured.'}

Always use the exact versions listed above. Do NOT suggest upgrading or using features from newer versions unless explicitly asked.

## Active components

**Rules installed:** ${rulesList || 'common'}
**Skills installed:** ${skillsList || 'coding-standards, security-review, tdd-workflow'}
**Agents installed:** ${agentsList || 'planner, architect'}

## Workflow

This project uses **RapidX** workflow engine for structured SDLC delivery.

Key commands:
- \`/rapidx:new-project\` — Start a new project with requirements and roadmap
- \`/rapidx:plan-phase\` — Plan the next development phase
- \`/rapidx:execute-phase\` — Execute current phase with parallel tasks
- \`/rapidx:verify-work\` — Verify completed work against requirements
- \`/rapidx:review\` — Code review current changes
- \`/rapidx:ship\` — Prepare release
- \`/rapidx:do\` — Smart dispatcher — describe what you want

RapidX commands:
- \`/rapidx:help\` — Show all RapidX commands
- \`/rapidx:switch-client\` — Change client profile
- \`/rapidx:add-tech\` — Add a technology to the stack
- \`/rapidx:governance-check\` — Run governance audit

## Coding standards

Follow all rules in the active ruleset. Key principles:
- Write clean, readable, self-documenting code
- Handle all errors explicitly with \`[RapidX]\` prefix on log messages
- Use \`path.join()\` for all file paths (never hardcoded separators)
- No external npm dependencies unless explicitly approved
- All secrets via environment variables — never hardcoded
- Immutable data patterns preferred
- Functions under 50 lines, files under 800 lines

## Review gates

${reviewGates || '- Standard code review required before merge\n- Security review for auth/payment/data changes'}
${governanceSection}
## Config

Stack config: \`.rapidx/stack.json\`
Profile: \`profiles/${profileId}.json\`
`;
}

/**
 * Write CLAUDE.md to a directory.
 * @param {string} targetDir
 * @param {object} profile
 * @param {object} stack
 * @param {object} components
 */
function writeClaudeMd(targetDir, profile, stack, components) {
  const content = generateClaudeMd(profile, stack, components);
  const outPath = path.join(targetDir, 'CLAUDE.md');
  fs.writeFileSync(outPath, content, 'utf8');
  return outPath;
}

module.exports = { generateClaudeMd, writeClaudeMd };
