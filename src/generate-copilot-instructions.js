'use strict';

const fs = require('fs');
const path = require('path');

/**
 * Generate .github/copilot-instructions.md content.
 * This is the primary file GitHub Copilot reads for project-level instructions.
 * @param {object} profile
 * @param {object} stack
 * @param {object} components
 * @returns {string}
 */
function generateCopilotInstructions(profile, stack, components) {
  const clientName = profile.client_name || 'RapidX Project';
  const profileId = profile.profile_id || 'default';

  const fe = stack.frontend || {};
  const be = stack.backend || {};
  const db = stack.database || {};
  const infra = stack.infrastructure || {};
  const testing = stack.testing || {};

  const skills = components ? Array.from(components.skills) : (profile.skills || []);
  const rules = components ? Array.from(components.rules) : (profile.rules || []);

  // Version constraints
  const constraints = [];
  if (fe.framework && fe.version) {
    constraints.push(`- **${fe.framework}**: Use version ${fe.version} APIs only. Do NOT suggest ${fe.framework} features introduced after ${fe.version}.`);
  }
  if (be.language && be.language_version) {
    constraints.push(`- **${be.language}**: Use version ${be.language_version} features only.`);
  }
  if (be.framework && be.framework_version) {
    constraints.push(`- **${be.framework}**: Use version ${be.framework_version} APIs only.`);
  }
  if (db.primary && db.primary_version) {
    constraints.push(`- **${db.primary}**: Use version ${db.primary_version} syntax/features only.`);
  }
  if (db.orm && db.orm_version) {
    constraints.push(`- **${db.orm}**: Use version ${db.orm_version} APIs only.`);
  }

  // Coding standards from rules
  const codingStandards = [
    '- Write clean, readable, self-documenting code',
    '- Handle all errors explicitly — never swallow exceptions',
    '- Use immutable data patterns where possible',
    '- Functions under 50 lines, files under 800 lines',
    '- All secrets via environment variables — never hardcode credentials',
    '- Validate all user input at system boundaries',
  ];

  if (rules.includes('typescript')) {
    codingStandards.push('- Strict TypeScript: no `any` types, explicit return types on public functions');
    codingStandards.push('- Use `const` by default, `let` only when reassignment is necessary');
  }
  if (rules.includes('python')) {
    codingStandards.push('- Follow PEP 8 style guide');
    codingStandards.push('- Use type hints on all function signatures');
    codingStandards.push('- Prefer dataclasses or Pydantic models over plain dicts');
  }
  if (rules.includes('golang')) {
    codingStandards.push('- Follow effective Go style: short variable names, explicit error handling');
    codingStandards.push('- Always handle errors — never use `_` for error values in production code');
  }

  const skillRefs = skills.map(s => `- [\`${s}\`](.github/copilot/skills/${s}.md)`).join('\n');

  return `# GitHub Copilot Instructions — ${clientName}

> Generated by RapidX Agentic Engineering Platform
> Profile: ${profileId} | Generated: ${new Date().toISOString()}

## Project context

**Client:** ${clientName}
**Profile:** ${profileId}
**Maturity level:** ${(profile.engagement && profile.engagement.maturity_level) || 'L1'}

This project uses the **Get Things Done** workflow engine for structured SDLC delivery, combined with the **Everything Claude Code** component library for coding standards and patterns.

## Technology stack

${fe.framework ? `**Frontend:** ${fe.framework}${fe.version ? ' ' + fe.version : ''}${fe.ui_library && fe.ui_library.length ? ' + ' + fe.ui_library.join(', ') : ''}` : ''}
${be.language ? `**Backend:** ${be.language}${be.language_version ? ' ' + be.language_version : ''}${be.framework ? ' + ' + be.framework + (be.framework_version ? ' ' + be.framework_version : '') : ''}` : ''}
${be.api_style && be.api_style.length ? `**API style:** ${be.api_style.join(', ')}` : ''}
${db.primary ? `**Database:** ${db.primary}${db.primary_version ? ' ' + db.primary_version : ''}${db.orm ? ' + ' + db.orm : ''}` : ''}
${db.cache && db.cache.length ? `**Cache:** ${db.cache.join(', ')}` : ''}
${infra.cloud ? `**Cloud:** ${infra.cloud}` : ''}
${infra.cicd && infra.cicd.length ? `**CI/CD:** ${infra.cicd.join(', ')}` : ''}
${testing.unit && testing.unit.length ? `**Testing:** ${[...(testing.unit || []), ...(testing.e2e || [])].join(', ')}` : ''}

## Version constraints (CRITICAL)

When generating code, always use the exact versions above:

${constraints.length ? constraints.join('\n') : '- Use stable, widely-supported APIs for the configured tech stack.'}

## Coding standards

${codingStandards.join('\n')}

## Security requirements

- Never hardcode API keys, passwords, tokens, or secrets
- Always validate and sanitize user input
- Use parameterized queries — never string concatenation for SQL
- Implement proper authentication and authorization checks
- Log security events but never log sensitive data
- Use HTTPS and secure headers in all web applications

## Available skills (reference files)

${skillRefs || 'Skills are defined in `.github/copilot/skills/`'}

## Workflow commands

Use these commands in Copilot Chat or Claude Code:

\`\`\`
/gsd:new-project      Start a new project with structured planning
/gsd:plan-phase       Plan the next development phase
/gsd:execute-phase    Execute current phase tasks
/gsd:verify-work      Verify completed work
/gsd:review           Code review and quality check
/gsd:ship             Prepare for release
/rapidx:help          Show all RapidX commands
/rapidx:switch-client Change active client profile
\`\`\`

## Review gates

Before submitting code for review:
- [ ] All tests pass
- [ ] No hardcoded secrets or credentials
- [ ] Error handling is explicit at all levels
- [ ] Code follows the standards listed above
- [ ] Security implications reviewed for auth/data changes
`;
}

/**
 * Write copilot-instructions.md to .github/ directory.
 */
function writeCopilotInstructions(targetDir, profile, stack, components) {
  const content = generateCopilotInstructions(profile, stack, components);
  const githubDir = path.join(targetDir, '.github');
  fs.mkdirSync(githubDir, { recursive: true });
  const outPath = path.join(githubDir, 'copilot-instructions.md');
  fs.writeFileSync(outPath, content, 'utf8');
  return outPath;
}

module.exports = { generateCopilotInstructions, writeCopilotInstructions };
